/* ------------------------------------------------------------------ *
 * Starter packages — the "total package" the owner quotes from.
 *
 * A fixed tier is a concrete bill of materials with a customer price.
 * A built-to-order package is a recipe on a per-kWp basis, so it scales
 * to any size and the inverter / battery are chosen to match the final
 * size. Both carry roughly a 30% margin at the placeholder prices.
 *
 * Every number here is editable in the backoffice afterwards.
 * ------------------------------------------------------------------ */

export type StarterPackageItem = {
  /** Model of a product in this catalogue. Empty for a generic allowance line. */
  model: string;
  label: string;
  qty: number;
  /** "each" for a fixed bill of materials, "per_kwp" for a recipe that scales. */
  basis: "each" | "per_kwp";
  /** Used only when `model` is empty — a cost allowance per unit, in centavos. */
  unitCostMinor: number;
};

export type StarterPackage = {
  name: string;
  sizeKwp: number;
  kind: "fixed" | "custom";
  /** Fixed tiers carry the customer price. A built-to-order package prices from markup. */
  sellPriceMinor: number;
  markupPct: number;
  description: string;
  items: StarterPackageItem[];
};

